// The XML vector-drawable resource-loading pipeline on the wasmJs target silently fails to
// resolve any drawable added after the project's original resource set (confirmed: the request
// fetches correctly over HTTP, no console/JS error is thrown, a byte-for-byte copy of an
// already-working file under a new name still fails, and forcing a full resource-codegen
// rebuild doesn't change it — so it isn't caching, CSP, strokeWidth, or file content). Desktop
// and Android are unaffected; only wasmJs. Defining these as ImageVectors sidesteps the runtime
// resource fetch entirely — they're compiled Kotlin, not an asset loaded asynchronously — so
// this works identically on every target, including web. Path data is copied verbatim from the
// original btc.xml/stock.xml path outlines. The stroke color set here is inconsequential since
// Icon(tint = ...) always overrides it with a ColorFilter — it's only a valid placeholder value.

private fun boldVector(
    name: String,
    viewportSize: Float,
    pathData: String,
): ImageVector =
    ImageVector
        .Builder(
            name = name,
            defaultWidth = 100.dp,
            defaultHeight = 100.dp,
            viewportWidth = viewportSize,
            viewportHeight = viewportSize,
        ).addPath(
            pathData = PathParser().parsePathString(pathData).toNodes(),
            fill = null,
            stroke = SolidColor(Color(0xFF008000)),
            strokeLineWidth = 14f,
        ).build()

